#!/usr/bin/env node
// Writes apps/web/src/lib/card-glyphs.ts: how wide each character is in DM Sans as the site
// serves it, at the weights the story card uses (lib/masonry.ts wraps card text with these, D55).
// Measured in Chromium from the built site's latin DM Sans (next/font downloads it at build), at
// 100 px without hinting, so the widths are the font's own (in thousandths of an em). Run after
// `pnpm nx run web:prune` whenever the font changes:
//   node tools/scripts/card-glyph-widths.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { chromium } from '@playwright/test';

const root = resolve(import.meta.dirname, '../..');
const statics = join(root, 'apps/web/dist/apps/web/.next/static');
const out = join(root, 'apps/web/src/lib/card-glyphs.ts');

/** story-card.tsx's weights: its text (italic is the same face, slanted) and its title. */
const WEIGHTS = [400, 600];
/** Printable ASCII, Latin-1 and the usual typographic punctuation. */
const CHARS = [
  ...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)),
  ...Array.from({ length: 95 }, (_, i) => String.fromCharCode(0xa1 + i)),
  ...'‐‑‒–—―‘’‚“”„†‡•…‰′″‹›€™',
];

// The latin face: the @font-face whose unicode-range starts with U+0000-00FF (U+??).
function latinFont() {
  const dir = join(statics, 'chunks');
  for (const file of readdirSync(dir, { recursive: true })) {
    if (!String(file).endsWith('.css')) continue;
    const css = readFileSync(join(dir, String(file)), 'utf8');
    for (const face of css.match(/@font-face\{[^}]*\}/g) ?? []) {
      const src =
        /family:DM Sans;.*url\(\.\.\/media\/([^)]+)\).*unicode-range:U\+\?\?/.exec(
          face,
        );
      if (src) return join(statics, 'media', src[1]);
    }
  }
  throw new Error(
    'No latin DM Sans in the build: run `pnpm nx run web:prune` first.',
  );
}

const font = readFileSync(latinFont()).toString('base64');
const browser = await chromium.launch();
const page = await browser.newPage();
const measured = await page.evaluate(
  async ({ font, weights, chars }) => {
    const bytes = Uint8Array.from(atob(font), (c) => c.charCodeAt(0));
    const face = new FontFace('Card', bytes.buffer, { weight: '100 1000' });
    await face.load();
    document.fonts.add(face);
    const span = document.createElement('span');
    span.style.cssText =
      'font:100px Card;white-space:pre;position:absolute;text-rendering:geometricPrecision';
    document.body.append(span);
    const width = (text) => {
      span.textContent = text;
      return span.getBoundingClientRect().width;
    };
    const result = {};
    for (const weight of weights) {
      span.style.fontWeight = String(weight);
      // A space between two letters, as it sits in text.
      result[weight] = chars.map((ch) =>
        ch === ' ' ? width('x x') - width('xx') : width(ch.repeat(10)) / 10,
      );
    }
    return result;
  },
  { font, weights: WEIGHTS, chars: CHARS },
);
await browser.close();

// Thousandths of an em (the widths are at 100 px), rounded up so sums err wide, never narrow.
const rows = Object.entries(measured).map(
  ([weight, widths]) =>
    `  ${weight}: [${widths.map((w) => Math.ceil(w * 10)).join(',')}],`,
);
writeFileSync(
  out,
  `// Generated by tools/scripts/card-glyph-widths.mjs: don't edit by hand.
// DM Sans's character widths by weight, in thousandths of an em, for each of GLYPH_CHARS in turn
// (lib/masonry.ts wraps card text with them).

export const GLYPH_CHARS = ${JSON.stringify(CHARS.join(''))};

export const GLYPH_WIDTHS = {
${rows.join('\n')}
} as const;
`,
);
console.log(`Wrote ${out}`);
